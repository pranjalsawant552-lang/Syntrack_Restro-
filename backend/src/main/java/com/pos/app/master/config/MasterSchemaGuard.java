package com.pos.app.master.config;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.context.annotation.DependsOn;
import org.springframework.core.Ordered;
import org.springframework.core.annotation.Order;
import org.springframework.stereotype.Component;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/**
 * Runs first at start-up and checks that Hibernate really created the master tables.
 *
 * Why: Hibernate's "update" only LOGS a warning when a CREATE TABLE fails (for example "permission denied for schema
 * public" on PostgreSQL 15+, or a wrong DB_NAME / DB_USERNAME) and the app then carries on and crashes later with a
 * confusing 'relation "super_admins" does not exist'. This guard stops right away and prints the real cause and the fix.
 */
@Component
@DependsOn("masterEntityManagerFactory")
@Order(Ordered.HIGHEST_PRECEDENCE)
public class MasterSchemaGuard implements ApplicationRunner {

    private static final Logger log = LoggerFactory.getLogger(MasterSchemaGuard.class);

    /** Physical table names of the master entities (SuperAdmin, Tenant, TenantUserIndex). */
    private static final List<String> REQUIRED = List.of("super_admins", "tenants", "tenant_user_index");

    /**
     * Same tables Hibernate would build from the master entities (SnakeCase names). Used only as a safety net when
     * Hibernate's own "update" did not create them; IF NOT EXISTS keeps it harmless and Hibernate's normal update
     * on the next start simply finds the tables already there.
     */
    private static final Map<String, String> DDL = Map.of(
            "super_admins",
            "CREATE TABLE IF NOT EXISTS super_admins ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "first_name VARCHAR(255), last_name VARCHAR(255), "
                    + "email VARCHAR(255), password VARCHAR(255), "
                    + "active BOOLEAN NOT NULL DEFAULT TRUE, token_version INTEGER NOT NULL DEFAULT 0, "
                    + "created_at TIMESTAMP(6), "
                    + "CONSTRAINT uk_super_admins_email UNIQUE (email))",
            "tenants",
            "CREATE TABLE IF NOT EXISTS tenants ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "name VARCHAR(255), slug VARCHAR(255), db_name VARCHAR(255), "
                    + "contact_email VARCHAR(255), contact_phone VARCHAR(255), logo_url VARCHAR(255), "
                    + "active BOOLEAN NOT NULL DEFAULT TRUE, max_users INTEGER, max_products INTEGER, "
                    + "created_at TIMESTAMP(6), updated_at TIMESTAMP(6), "
                    + "CONSTRAINT uk_tenants_slug UNIQUE (slug), CONSTRAINT uk_tenants_db_name UNIQUE (db_name))",
            "tenant_user_index",
            "CREATE TABLE IF NOT EXISTS tenant_user_index ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "email VARCHAR(255), tenant_id BIGINT, tenant_slug VARCHAR(255), "
                    + "CONSTRAINT uk_tenant_user_index_email UNIQUE (email))");

    private final DataSource masterDataSource;

    public MasterSchemaGuard(@Qualifier("masterDataSource") DataSource masterDataSource) {
        this.masterDataSource = masterDataSource;
    }

    @Override
    public void run(ApplicationArguments args) {
        try (Connection c = masterDataSource.getConnection()) {
            List<String> missing = new ArrayList<>();
            for (String table : REQUIRED) {
                if (!tableExists(c, table)) missing.add(table);
            }
            if (missing.isEmpty()) return;

            // Safety net: create the missing tables ourselves (works whenever this user may create tables).
            String createError = createMissing(c, missing);
            if (createError == null) {
                log.warn("Hibernate had not created the master table(s) {} - created them now. If this repeats on every "
                        + "start, check the console for an earlier 'Error executing DDL' warning.", missing);
                return;
            }

            String where = describe(c);
            String probeError = createError;

            StringBuilder msg = new StringBuilder();
            msg.append("\n\n================ MASTER DATABASE IS NOT READY ================\n");
            msg.append("Missing table(s): ").append(missing).append("\n");
            msg.append("Connected as: ").append(where).append("\n");
            if (probeError != null) {
                msg.append("Cannot create tables here -> ").append(probeError).append("\n");
            } else {
                msg.append("The user CAN create tables, so look further UP in this console for a line like\n")
                   .append("  'GenerationTarget encountered exception accepting command : Error executing DDL ...'\n")
                   .append("- that line names the exact statement that failed.\n");
            }
            msg.append("\nFix (pick the one that matches):\n")
               .append(" 1) 'permission denied for schema public' (PostgreSQL 15+): run in psql as a superuser:\n")
               .append("      GRANT ALL ON SCHEMA public TO <db user>;  ALTER DATABASE <db name> OWNER TO <db user>;\n")
               .append(" 2) Wrong database/user: check DB_HOST, DB_PORT, DB_NAME (default 'syntrack'), DB_USERNAME,\n")
               .append("    DB_PASSWORD in the IntelliJ run configuration (Environment variables).\n")
               .append(" 3) Fresh start on a dev machine: DROP DATABASE syntrack; (the app re-creates it and all tables).\n")
               .append("==============================================================\n");
            log.error(msg.toString());
            throw new IllegalStateException("Master database tables missing " + missing
                    + " - see the MASTER DATABASE IS NOT READY message above");
        } catch (SQLException e) {
            throw new IllegalStateException("Could not check the master database: " + e.getMessage(), e);
        }
    }

    private static boolean tableExists(Connection c, String table) throws SQLException {
        String sql = "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = ?";
        try (PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, table);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() && rs.getLong(1) > 0;
            }
        }
    }

    private static String describe(Connection c) {
        try (Statement st = c.createStatement();
             ResultSet rs = st.executeQuery("SELECT current_database(), current_user, current_schema()")) {
            if (rs.next()) {
                return "database=" + rs.getString(1) + ", user=" + rs.getString(2) + ", schema=" + rs.getString(3);
            }
        } catch (SQLException ignored) {
            // purely informational
        }
        return "(unknown)";
    }

    /** Creates the missing master tables; returns the database's own error text, or null if all now exist. */
    private static String createMissing(Connection c, List<String> missing) {
        boolean previous = true;
        try {
            previous = c.getAutoCommit();
            c.setAutoCommit(true);
            try (Statement st = c.createStatement()) {
                for (String table : missing) {
                    st.execute(DDL.get(table));
                }
            }
            for (String table : missing) {
                if (!tableExists(c, table)) return "table " + table + " still missing after CREATE TABLE";
            }
            return null;
        } catch (SQLException e) {
            return e.getMessage();
        } finally {
            try {
                c.setAutoCommit(previous);
            } catch (SQLException ignored) {
                // connection is closed right after
            }
        }
    }
}
